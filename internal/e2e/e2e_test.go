var env *pebble.Env

func TestMain(m *testing.M) {
	code := func() int {
		var stop func()
		var err error
		env, stop, err = pebble.Start()
		if err != nil {
			fmt.Fprintln(os.Stderr, "e2e tests disabled:", err)
		} else {
			defer stop()
		}
		return m.Run()
	}()
	os.Exit(code)
}

type client struct {
	t     *testing.T
	base  string
	token string
}

func (c *client) call(method, path string, body any, want int, out any) {
	c.t.Helper()
	var rd io.Reader
	if body != nil {
		b, _ := json.Marshal(body)
		rd = bytes.NewReader(b)
	}
	req, _ := http.NewRequest(method, c.base+path, rd)
	req.Header.Set("Content-Type", "application/json")
	if c.token != "" {
		req.Header.Set("Authorization", "Bearer "+c.token)
	}
	resp, err := http.DefaultClient.Do(req)
	if err != nil {
		c.t.Fatal(err)
	}
	defer resp.Body.Close()
	raw, _ := io.ReadAll(resp.Body)
	if resp.StatusCode != want {
		c.t.Fatalf("%s %s: %d, want %d: %s", method, path, resp.StatusCode, want, raw)
	}
	if out != nil {
		if s, ok := out.(*string); ok {
			*s = string(raw)
			return
		}
		if err := json.Unmarshal(raw, out); err != nil {
			c.t.Fatalf("%s %s: %v: %s", method, path, err, raw)
		}
	}
}

func TestACMEThroughAPI(t *testing.T) {
	if env == nil {
		t.Skip("pebble not available")
	}
	ctx := context.Background()
	if _, err := dnsresolver.Configure([]string{env.DNSAddr}, dnsresolver.ModeRecursiveOnly, nil); err != nil {
		t.Fatal(err)
	}

	st, err := store.Open(ctx, "sqlite:"+filepath.Join(t.TempDir(), "e2e.db"))
	if err != nil {
		t.Fatal(err)
	}
	defer st.Close()
	if err := st.Migrate(ctx); err != nil {
		t.Fatal(err)
	}
	kek, _ := secrets.NewLocalKEK(bytes.Repeat([]byte{9}, 32))
	vault := &secrets.Vault{Store: st, KEK: kek}
	reg := plugin.NewRegistry()
	reg.Register(func() plugin.Plugin { return &acme.Issuer{} })
	reg.Register(env.ChallDNSFactory())
	configs := &pluginconfig.Service{Store: st, Vault: vault, Registry: reg}
	log := slog.New(slog.NewTextHandler(io.Discard, nil))
	eng := &engine.Engine{Store: st, Vault: vault, Configs: configs, Log: log}
	srv := httptest.NewServer(api.New(api.Deps{Store: st, Log: log, Engine: eng, Configs: configs, Vault: vault}).Handler())
	defer srv.Close()

	hash, _ := auth.HashPassword("e2e admin password")
	st.CreateUser(ctx, "admin@example.com", "", hash, true)
	c := &client{t: t, base: srv.URL + "/api/v1"}
	var login struct{ Token string }
	c.call("POST", "/auth/login", map[string]string{"email": "admin@example.com", "password": "e2e admin password"}, 200, &login)
	c.token = login.Token

	c.call("POST", "/orgs", map[string]string{"slug": "acme"}, 201, nil)
	c.call("POST", "/orgs/acme/projects", map[string]string{"slug": "shop"}, 201, nil)
	c.call("PUT", "/orgs/acme/projects/shop/policy", map[string]any{"allowedNames": []string{"shop.example.com", "*.shop.example.com"}, "allowWildcard": true}, 200, nil)

	// The account key is generated by the server and never shown; the EAB
	// HMAC is a secret too.
	var issuer store.PluginConfig
	c.call("POST", "/orgs/acme/configs", map[string]any{
		"kind": "issuer", "plugin": "acme", "name": "pebble",
		"config": map[string]any{
			"directoryUrl": env.EABURL, "agreeToTerms": true, "profile": "default",
			"caCertificates": env.Roots, "eab": map[string]string{"keyId": pebble.EABKeyID, "hmacKey": pebble.EABHMAC},
		},
	}, 201, &issuer)
	cfg := string(issuer.Config)
	if strings.Contains(cfg, "PRIVATE KEY") || strings.Contains(cfg, pebble.EABHMAC) || strings.Count(cfg, pluginconfig.Redacted) != 2 {
		t.Fatalf("issuer config leaks or is not redacted: %s", cfg)
	}
	c.call("POST", "/orgs/acme/configs", map[string]any{"kind": "dns", "plugin": "pebble-dns", "name": "dns", "config": map[string]any{}}, 201, nil)

	// ACME needs a DNS provider; refuse up front rather than retry forever.
	c.call("POST", "/orgs/acme/projects/shop/certificates", map[string]any{
		"name": "nodns", "names": []string{"shop.example.com"}, "issuer": "pebble",
	}, 400, nil)
	c.call("POST", "/orgs/acme/projects/shop/certificates", map[string]any{
		"name": "shop", "names": []string{"shop.example.com", "*.shop.example.com"}, "issuer": "pebble", "dns": "dns",
	}, 202, nil)
	runAll(t, eng)

	var view struct {
		Status    string
		LastError string
		Current   *store.CertificateVersion
	}
	c.call("GET", "/orgs/acme/projects/shop/certificates/shop", nil, 200, &view)
	if view.Status != "active" || view.Current == nil {
		t.Fatalf("certificate = %+v", view)
	}
	if view.Current.ARICertID == "" || !view.Current.RenewAfter.Before(view.Current.NotAfter) {
		t.Fatalf("version = %+v", view.Current)
	}
	var pemChain string
	c.call("GET", "/orgs/acme/projects/shop/certificates/shop/versions/current/chain.pem", nil, 200, &pemChain)
	chain, err := certutil.ParseChainPEM([]byte(pemChain))
	if err != nil {
		t.Fatal(err)
	}
	if len(chain[0].DNSNames) != 2 || !strings.Contains(chain[0].Issuer.CommonName, "Pebble") {
		t.Fatalf("issued %v by %q", chain[0].DNSNames, chain[0].Issuer.CommonName)
	}

	// Renewal tells Pebble which certificate it replaces.
	c.call("POST", "/orgs/acme/projects/shop/certificates/shop/renew", nil, 202, nil)
	runAll(t, eng)
	var versions []store.CertificateVersion
	c.call("GET", "/orgs/acme/projects/shop/certificates/shop/versions", nil, 200, &versions)
	if len(versions) != 2 || versions[0].Fingerprint == versions[1].Fingerprint {
		t.Fatalf("versions = %+v", versions)
	}

	// Revoke the old one at the CA.
	c.call("POST", "/orgs/acme/projects/shop/certificates/shop/revoke", map[string]any{"version": versions[1].ID, "reason": 4}, 204, nil)
	c.call("GET", "/orgs/acme/projects/shop/certificates/shop/versions", nil, 200, &versions)
	if versions[1].RevokedAt == nil || versions[0].RevokedAt != nil {
		t.Fatalf("after revoke: %+v", versions)
	}
}

func runAll(t *testing.T, eng *engine.Engine) {
	t.Helper()
	for {
		ran, err := eng.RunOne(context.Background())
		if err != nil {
			t.Fatal(err)
		}
		if !ran {
			return
		}
	}
}
